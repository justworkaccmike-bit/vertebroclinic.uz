form.addEventListener("submit", async (e) => {
  e.preventDefault();
  let valid = true;
  ["name", "phone"].forEach((name) => {
    const input = form.elements[name];
    const ok = name === "phone" ? input.value.replace(/\D/g, "").length >= 9 : input.value.trim().length > 1;
    input.closest(".field").classList.toggle("is-invalid", !ok);
    if (!ok) valid = false;
  });
  if (!valid) return;

  await sendLead(Object.fromEntries(new FormData(form)));
  form.querySelector(".form__body").hidden = true;
  form.querySelector(".form__success").hidden = false;
});

// ===== Reveal on scroll =====
const revealTargets = document.querySelectorAll(".section__head, .card, .tabs, .checklist, .pkg-item, .diag, .step, .doc, .quote, .form, .stats");
